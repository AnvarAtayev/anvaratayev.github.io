def fmt_time(seconds: float) -> str:
    if seconds < 1e-6:
        return f"{seconds * 1e9:,.1f} ns"
    if seconds < 1e-3:
        return f"{seconds * 1e6:,.2f} µs"
    return f"{seconds * 1e3:,.2f} ms"


def fmt_bytes(n: float) -> str:
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024 or unit == "GiB":
            break
        n /= 1024
    return f"{n:,.0f} {unit}" if unit == "B" else f"{n:,.1f} {unit}"


def fmt_ratio(ratio: float) -> str:
    if ratio < 10:
        return f"{ratio:.1f}×"
    return f"{ratio:,.0f}×"


def fmt_value(value: float, memory: bool) -> str:
    return fmt_bytes(value) if memory else f"{fmt_time(value)}/op"


def cpu_name() -> str:
    """CPU brand string, e.g. "Apple M2"; the platform module can't name it."""
    if sys.platform == "darwin":
        cmd = ["sysctl", "-n", "machdep.cpu.brand_string"]
        return subprocess.check_output(cmd, text=True).strip()
    return platform.machine()


class Result(NamedTuple):
    label: str
    stmt: str
    setup: str
    value: float  # seconds per op, or peak bytes for kind="memory"


def spread(results: list[Result]) -> float:
    """Ratio of the worst case to the best."""
    values = [r.value for r in results]
    return max(values) / min(values)


def measure_memory(stmt: str, setup: str, repeat: int) -> int:
    """
    Lowest peak bytes allocated by one execution of stmt, over repeat runs.

    stmt is compiled outside the traced window so only its execution is measured; setup runs before tracing starts and is excluded too.
    """
    code = compile(stmt, "<benchmark>", "exec")
    peaks = []
    for _ in range(repeat):
        ns: dict[str, Any] = {}
        exec(setup, ns)
        gc.collect()
        tracemalloc.start()
        exec(code, ns)
        peaks.append(tracemalloc.get_traced_memory()[1])
        tracemalloc.stop()
    return min(peaks)


def run_benchmark(bench: Bench) -> list[Result]:
    memory = bench.get("kind") == "memory"
    repeat = bench.get("repeat", 3 if memory else 5)
    results = []
    for case in bench["cases"]:
        label, stmt = case[0], case[1]
        setup = case[2] if len(case) > 2 else bench.get("setup", "")
        if memory:
            value = measure_memory(stmt, setup, repeat)
        else:
            number = bench["number"]
            t = min(timeit.repeat(stmt, setup=setup, number=number, repeat=repeat))
            value = t / number
        results.append(Result(label, stmt, setup, value))
        print(f"  {label:16s} {fmt_value(value, memory)}", file=sys.stderr)
    return results


def snippet(results: list[Result]) -> str:
    """Render the code being measured as one python block: any shared setup
    first, then one `# label` block per case (with its setup if they differ).
    """
    shared = len({r.setup for r in results}) == 1
    blocks = [results[0].setup] if shared and results[0].setup else []
    for r in results:
        setup = "" if shared else f"{r.setup}\n"
        blocks.append(f"# {r.label}\n{setup}{r.stmt}")
    return "```python\n" + "\n\n".join(blocks) + "\n```"


def section(bench: Bench, results: list[Result]) -> str:
    memory = bench.get("kind") == "memory"
    best = min(r.value for r in results)
    rows = "\n".join(
        f"| `{r.label}` | {fmt_value(r.value, memory)} | {fmt_ratio(r.value / best)} |"
        for r in results
    )
    return "\n".join(
        [
            f"## {bench['title']} {{#{bench['slug']}}}",
            "",
            bench["note"],
            "",
            # Blank lines inside the div keep Goldmark parsing the markdown;
            # .bench-pair flexes the code and table side by side (see
            # assets/_custom.scss).
            '<div class="bench-pair">',
            "",
            snippet(results),
            "",
            f"| variant | {'peak memory' if memory else 'time'} | relative |",
            "|---|---:|---:|",
            rows,
            "",
            "</div>",
        ]
    )


def summary_table(all_results: list[tuple[Bench, list[Result]]]) -> str:
    lines = [
        "Each benchmark links to its measurement below: **winner** is the best variant, **ratio** is how many times worse the worst variant fared.",
        "",
        "| benchmark | type | winner | ratio | takeaway |",
        "|---|---|---|---:|---|",
    ]
    for bench, results in all_results:
        ratio = spread(results)
        # A ratio within noise of 1 has no meaningful winner.
        winner = (
            "-" if ratio < 1.05 else f"`{min(results, key=lambda r: r.value).label}`"
        )
        lines.append(
            f"| [{bench['title']}](#{bench['slug']}) | {bench.get('kind', 'speed')} "
            f"| {winner} | {fmt_ratio(ratio)} | {bench['takeaway']} |"
        )
    return "\n".join(lines)


def environment() -> str:
    return "\n".join(
        [
            f"- **Python**: {platform.python_version()} ({platform.python_implementation()})",
            f"- **Machine**: {cpu_name()}, {platform.platform(terse=True)}",
            f"- **Last run**: {date.today().isoformat()}",
            "",
        ]
    )


def main() -> None:
    all_results = []
    for bench in BENCHMARKS:
        print(f"{bench['slug']}...", file=sys.stderr)
        all_results.append((bench, run_benchmark(bench)))

    # Order summary rows and sections by impact, largest ratio first.
    # Round to display precision and tiebreak on slug so near-ties don't
    # reorder on timing jitter between runs.
    all_results.sort(key=lambda item: (-round(spread(item[1]), 1), item[0]["slug"]))

    speed = [(b, r) for b, r in all_results if b.get("kind") != "memory"]
    memory = [(b, r) for b, r in all_results if b.get("kind") == "memory"]

    body = "\n\n".join(
        [
            BEGIN,
            "# Environment",
            environment(),
            "# Summary",
            summary_table(all_results),
            "# Speed",
            *(section(b, r) for b, r in speed),
            "# Memory",
            *(section(b, r) for b, r in memory),
            END,
        ]
    )

    head, found_begin, rest = POST.read_text().partition(BEGIN)
    _, found_end, tail = rest.partition(END)
    if not (found_begin and found_end):
        sys.exit(f"error: BEGIN/END markers not found in {POST}")
    POST.write_text(head + body + tail)
    print(f"wrote {POST}", file=sys.stderr)


if __name__ == "__main__":
    main()
